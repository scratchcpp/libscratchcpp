#include <iomanip>
#include <sstream>

#include "cppcompilercontext.h"
#include "cppexecutablecode.h"

using namespace libscratchcpp;

static std::unordered_map<uint64_t, CppCompilerContext::CodeFactory> &codeRegistry()
{
    static std::unordered_map<uint64_t, CppCompilerContext::CodeFactory> registry;
    return registry;
}

static CppCompilerContext::SourceCallback &sourceCallback()
{
    static CppCompilerContext::SourceCallback callback;
    return callback;
}

CppCompilerContext::CppCompilerContext(IEngine *engine, Target *target, const std::unordered_set<std::string> &unsafeConstants) :
    CompilerContext(engine, target, unsafeConstants)
{
}

void CppCompilerContext::addProcedure(const std::string &procCode, std::shared_ptr<CppExecutableCode> code)
{
    m_procedures[procCode] = code;
}

CppExecutableCode *CppCompilerContext::procedure(const std::string &procCode) const
{
    auto it = m_procedures.find(procCode);
    return it == m_procedures.cend() ? nullptr : it->second.get();
}

/*! Returns the code which must be placed before generated sources. */
std::string CppCompilerContext::sourceHeader()
{
    return "// Generated by libscratchcpp\n\n#include <engine/internal/codegen/cpp/cppprelude.h>\n\nusing namespace libscratchcpp;\n\n";
}

/*! Returns the 64-bit FNV-1a hash of the given generated source. */
uint64_t CppCompilerContext::hash(const std::string &source)
{
    uint64_t ret = 14695981039346656037ULL;

    for (unsigned char c : source) {
        ret ^= c;
        ret *= 1099511628211ULL;
    }

    return ret;
}

/*! Returns the name of the generated class with the given source hash. */
std::string CppCompilerContext::className(uint64_t hash)
{
    std::stringstream ss;
    ss << "Code_" << std::hex << std::setw(16) << std::setfill('0') << hash;
    return ss.str();
}

/*! Registers generated code (called by generated code during static initialization). */
void CppCompilerContext::registerCode(uint64_t hash, CodeFactory factory)
{
    codeRegistry()[hash] = factory;
}

/*! Returns the factory of the generated code with the given source hash, or nullptr if it doesn't exist. */
CppCompilerContext::CodeFactory CppCompilerContext::findCode(uint64_t hash)
{
    auto &registry = codeRegistry();
    auto it = registry.find(hash);
    return it == registry.cend() ? nullptr : it->second;
}

/*! Sets a function which is called with the source of all built code (used to collect sources for codebase generation). */
void CppCompilerContext::setSourceCallback(const SourceCallback &callback)
{
    sourceCallback() = callback;
}

void CppCompilerContext::reportSource(uint64_t hash, const std::string &source)
{
    auto &callback = sourceCallback();

    if (callback)
        callback(hash, source);
}
