// Generates C++ code of the test cases, the generated code is compiled into cpp_test

#include <engine/internal/cpp/cppcompilercontext.h>
#include <fstream>
#include <iostream>

#include "cases.h"

using namespace libscratchcpp;

int main(int argc, char **argv)
{
    if (argc != 2) {
        std::cerr << "usage: " << argv[0] << " <output file>" << std::endl;
        return 1;
    }

    std::ofstream out(argv[1]);

    if (!out.is_open()) {
        std::cerr << "error: failed to open " << argv[1] << std::endl;
        return 1;
    }

    out << "// Generated by cpp_test_generator, do not edit\n\n" << CppCompilerContext::prelude() << "\n";

    for (const CppTestCase &testCase : cppTestCases()) {
        CppTestEnv env;
        testCase.build(env);
        out << "\n// Test case: " << testCase.name << "\n" << env.ctx->moduleSource();
    }

    return 0;
}
